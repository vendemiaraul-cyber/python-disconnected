// Pack the whole site into one Cloudflare Pages advanced-mode worker (dist/_worker.js):
// every file in public/ is inlined, and /api/proxy reuses functions/api/proxy.js.
// One file means a deployment is a single API request (see deploy.mjs).
import { readFileSync, writeFileSync, mkdirSync, readdirSync, statSync } from "node:fs";
import { join, relative, extname } from "node:path";

const root = new URL("..", import.meta.url).pathname;
const pub = join(root, "public");
const TYPES = { ".html": "text/html; charset=utf-8", ".css": "text/css; charset=utf-8", ".js": "text/javascript; charset=utf-8", ".svg": "image/svg+xml", ".json": "application/json", ".txt": "text/plain; charset=utf-8" };

const assets = {};
(function walk(dir) {
  for (const name of readdirSync(dir)) {
    const full = join(dir, name);
    if (statSync(full).isDirectory()) { walk(full); continue; }
    if (name.startsWith("_")) continue; // _headers is applied in code below
    const type = TYPES[extname(name)];
    if (!type) throw new Error(`no content type for ${name}`);
    assets["/" + relative(pub, full).split("\\").join("/")] = { type, body: readFileSync(full, "utf8") };
  }
})(pub);

const proxySrc = readFileSync(join(root, "functions/api/proxy.js"), "utf8").replace(/^export async function onRequestGet/m, "async function proxyGet");

const worker = `// Generated by scripts/build-worker.mjs — do not edit.
${proxySrc}

const ASSETS = ${JSON.stringify(assets)};
const SECURITY = {
  "x-content-type-options": "nosniff",
  "referrer-policy": "strict-origin-when-cross-origin",
  "x-frame-options": "DENY",
  "permissions-policy": "camera=(), microphone=(), geolocation=()",
};

export default {
  async fetch(request) {
    const url = new URL(request.url);
    if (url.pathname === "/api/proxy") {
      if (request.method !== "GET") return new Response("method not allowed", { status: 405 });
      const res = await proxyGet({ request });
      const out = new Response(res.body, res);
      for (const [k, v] of Object.entries(SECURITY)) out.headers.set(k, v);
      return out;
    }
    if (request.method !== "GET" && request.method !== "HEAD") return new Response("method not allowed", { status: 405 });
    const path = url.pathname === "/" ? "/index.html" : url.pathname;
    const asset = ASSETS[path];
    if (!asset) return new Response("Not found", { status: 404, headers: { "content-type": "text/plain", ...SECURITY } });
    return new Response(request.method === "HEAD" ? null : asset.body, {
      headers: {
        "content-type": asset.type,
        "cache-control": path === "/index.html" ? "no-cache" : "public, max-age=300",
        ...SECURITY,
      },
    });
  },
};
`;
mkdirSync(join(root, "dist"), { recursive: true });
writeFileSync(join(root, "dist/_worker.js"), worker);
console.log(`dist/_worker.js: ${Object.keys(assets).length} files inlined, ${(worker.length / 1024).toFixed(0)} KB`);
